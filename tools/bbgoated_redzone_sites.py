#!/usr/bin/env python3
"""Writes src/host/redzone_sites.inc from a redzone.json (Supermedo/bloodborne_pc
PR #2, DarkSpartan, GPL-2.0-or-later: tools/redzone_sites.py's list of the stores
of the 1.09 eboot's red-zone leaf functions). Each site becomes {image offset, length}.

    python tools/bbgoated_redzone_sites.py <redzone.json> > src/host/redzone_sites.inc
"""
import json
import sys

d = json.load(open(sys.argv[1], encoding="utf-8"))
sites = sorted((off, len(bytes.fromhex(hexbytes))) for off, hexbytes, _lens in d["sites"])
print("// Generated by tools/bbgoated_redzone_sites.py from Supermedo/bloodborne_pc PR #2's")
print("// patches/redzone.json (DarkSpartan, GPL-2.0-or-later): %d store sites in %d red-zone leaf"
      % (len(sites), d["functions"]))
print("// functions of the 1.09 eboot, as {image offset, length}; text sha256 %s." % d["text_sha256"])
for off, n in sites:
    print("{0x%x, %d}," % (off, n))
